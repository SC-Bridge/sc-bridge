/** Humanize a faction slug: known lookup, then camelCase split, then fallback word split */
export function humanizeFactionSlug(slug) {
  if (!slug) return ''
  const lower = slug.toLowerCase()
  if (FACTION_SLUG_NAMES[lower]) return FACTION_SLUG_NAMES[lower]
  // Strip "lawful_" / "unlawful_" prefix and retry
  const stripped = lower.replace(/^(?:lawful|unlawful)_/, '')
  if (FACTION_SLUG_NAMES[stripped]) return FACTION_SLUG_NAMES[stripped]
  // Split camelCase: "BountyHuntersGuild" → "Bounty Hunters Guild"
  const spaced = slug.replace(/([a-z])([A-Z])/g, '$1 $2')
  if (spaced !== slug) return spaced
  // Snake_case fallback: title-case each word
  return slug.replace(/_/g, ' ')
    .split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ')
}

/** Humanize a scope slug: known lookup, then snake_case/camelCase split + title-case */
export function humanizeScopeSlug(slug) {
  if (!slug) return ''
  const lower = slug.toLowerCase()
  if (SCOPE_SLUG_NAMES[lower]) return SCOPE_SLUG_NAMES[lower]
  return slug.replace(/_/g, ' ').replace(/([a-z])([A-Z])/g, '$1 $2')
    .split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ')
}

/** Humanize a standing slug: known patterns, then fallback split + title-case */
export function humanizeStandingSlug(slug) {
  if (!slug) return ''
  // Handle affinity patterns: "affinity_enemy_-005" → "Not Hostile".
  // 4.8 prefixes these with "reputationstanding_" (e.g.
  // "reputationstanding_affinity_enemy_-005"), so match on a segment boundary
  // (start OR underscore) rather than the string start — otherwise the prefix
  // breaks the match and the slug falls through to the raw "-005" fallback.
  const affinityMatch = slug.match(/(?:^|_)affinity_(enemy|friend|neutral|ally)_?(-?\d*)$/i)
  if (affinityMatch) {
    const type = affinityMatch[1].toLowerCase()
    if (type === 'enemy') return 'Not Hostile'
    if (type === 'friend' || type === 'ally') return 'Friendly'
    return 'Neutral'
  }
  // Handle NPC reliability: "npc_fired_fired" → skip (internal game data)
  if (slug.match(/^npc_/i)) return null
  // Known rank/standing names — checked against the last segment of compound slugs
  const STANDING_NAMES = {
    applicant: 'Applicant', probation: 'Probation',
    agent: 'Agent', masteragent: 'Master Agent', senioragent: 'Senior Agent',
    junioragent: 'Junior Agent', veteranagent: 'Veteran Agent',
    tracker: 'Tracker', advancedtracker: 'Advanced Tracker',
    seniortracker: 'Senior Tracker', mastertracker: 'Master Tracker',
    neutral: 'Neutral', hostile: 'Hostile', friendly: 'Friendly',
    noteligible: 'Not Eligible', outsider: 'Outsider', counsel: 'Counsel',
    senior: 'Senior', junior: 'Junior', veteran: 'Veteran',
  }
  // Handle "rank4", "hauling_rank4", "security_rank4" etc.
  const rankMatch = slug.match(/(?:^|_)rank(\d+)$/i)
  if (rankMatch) {
    return `Rank ${rankMatch[1]}`
  }
  // Split on underscores, check if the LAST segment (or last 2 joined) is a known standing name
  const parts = slug.toLowerCase().split('_')
  // Try last segment: "bounty_applicant" → "applicant" → "Applicant"
  if (STANDING_NAMES[parts[parts.length - 1]]) {
    return STANDING_NAMES[parts[parts.length - 1]]
  }
  // Try last two segments joined: "bounty_masteragent_bountyhuntersguild" → skip guild suffix, try "masteragent"
  // Try each segment from the end until we find a known name
  for (let i = parts.length - 1; i >= 0; i--) {
    if (STANDING_NAMES[parts[i]]) return STANDING_NAMES[parts[i]]
    // Try joined pair: "veteranagent" from "veteran" + "agent"? No, these are already single slugs
  }
  // Standalone known slugs
  const lower = slug.toLowerCase()
  if (STANDING_NAMES[lower]) return STANDING_NAMES[lower]
  // Fallback: title-case the last meaningful segment
  const lastPart = parts[parts.length - 1]
  return lastPart.charAt(0).toUpperCase() + lastPart.slice(1)
}

/** Humanize comparison operator */
export function humanizeComparison(cmp) {
  // DB stores CIG's long-form values (GreaterThanOrEqualTo, etc.);
  // short aliases kept for backwards compatibility.
  const map = {
    GreaterThanOrEqualTo: 'or higher',
    LessThanOrEqualTo: 'or lower',
    GreaterThan: 'above',
    LessThan: 'below',
    EqualTo: 'exactly',
    NotEqualTo: 'other than',
    gte: 'or higher', lte: 'or lower', gt: 'above', lt: 'below', eq: 'exactly',
  }
  return map[cmp] || cmp
}

/** Format a full reputation requirement into a player-friendly string */
export function formatRepRequirement(r) {
  const standing = humanizeStandingSlug(r.standing_slug)
  if (!standing) return null // Skip NPC reliability etc.
  const faction = humanizeFactionSlug(r.faction_slug)
  const scope = humanizeScopeSlug(r.scope_slug)
  const cmp = humanizeComparison(r.comparison)
  // For affinity scope: express as a simple relationship statement
  // "Not Hostile" + "above" + "Eckhart Security" → "Not hostile with Eckhart Security"
  // "Friendly" + "or higher" + "BHG" → "Friendly with BHG"
  const isAffinity = r.scope_slug === 'affinity' || r.standing_slug?.startsWith('affinity_')
  if (isAffinity) {
    return { label: `${standing} with ${faction}`, standing: null, cmp: null, faction: null, scope: null }
  }
  // Career scopes: "Agent or higher with BHG (Bounty)"
  // Suppress scope if it's redundant with the faction name (e.g. "Bounty (BHG)" after "Bounty Hunters Guild")
  const showScope = scope && !scope.toLowerCase().includes('bhg') && scope !== faction
  return { label: null, standing, cmp, faction, scope: showScope ? scope : null }
}

/**
 * Derive the set of reputation SCOPE slugs a mission affects, for the Career
 * Reputation browse view + the `?rep=` scope filter.
 *
 * 4.8 moved scope out of `rep_summary` (now a bare success magnitude like "XS")
 * into the structured `rep_changes` rows and the legacy `rep_fail`/`rep_abandon`
 * strings ("affinity: -XXXXS, security: -M"). Prefer the structured rows; fall
 * back to parsing the legacy strings. Internal engine scopes (npc_reliability)
 * are excluded so they never appear as a browsable track.
 *
 * @param {Array<{scope_slug:string}>|null} changes structured rep_changes rows
 * @param {string|null} repFail legacy "scope: -SIZE, ..." fail string
 * @param {string|null} repAbandon legacy abandon string
 * @returns {string[]} unique, lowercased scope slugs (excludes internal scopes)
 */
export function deriveRepScopeSlugs(changes, repFail, repAbandon) {
  const slugs = new Set()
  if (changes && changes.length) {
    for (const c of changes) if (c.scope_slug) slugs.add(c.scope_slug.toLowerCase())
  } else {
    const re = /([a-zA-Z_]+)\s*:\s*[+\-]\s*[a-zA-Z]+/g
    for (const s of [repFail, repAbandon]) {
      if (!s) continue
      let m
      while ((m = re.exec(s)) !== null) slugs.add(m[1].toLowerCase())
    }
  }
  return [...slugs].filter(s => s && !REP_SCOPE_EXCLUDE.has(s))
}

